String pendingName = "";

void enrollStart(const String& name) {
  pendingName = name;
  fp_resetTemplates();
  enrollState = ENROLL_IDLE;
  processingStartMs = 0;
  updateLeds();
  Serial.println("[Enroll] Started for: " + name);
}

void enrollScan1() {
  if (enrollState != ENROLL_IDLE) return;        // only valid from idle
  if (fp_captureTemplate1()) {
    enrollState = ENROLL_SCAN1_DONE;             // scan 1 done, waiting for scan 2
    updateLeds();
    Serial.println("[Enroll] Template 1 captured: " + fp_template1);
  }
}

void enrollScan2() {
  if (enrollState != ENROLL_SCAN1_DONE) return;  // only valid after scan 1
  if (fp_captureTemplate2()) {
    enrollState = ENROLL_SCAN2_DONE;             // scan 2 done, processing auto-starts
    processingStartMs = millis();
    updateLeds();
    Serial.println("[Enroll] Template 2 captured: " + fp_template2);
  }
}

// Called from loop() — drives automatic processing after scan 2
void enrollProcessLoop() {
  if (enrollState == ENROLL_SCAN2_DONE) {
    unsigned long elapsed = millis() - processingStartMs;
    if (elapsed > PROCESSING_TIMEOUT_MS) {
      enrollState = ENROLL_FAILED;
      updateLeds();
      Serial.println("[Enroll] FAILED — processing timeout");
      return;
    }
    if (elapsed > 1500) {
      enrollState = ENROLL_PROCESSING;
      updateLeds();
    }
  }
  if (enrollState == ENROLL_PROCESSING) {
    unsigned long elapsed = millis() - processingStartMs;
    if (elapsed > 3000) {
      String uid = fp_combineToUID();
      if (uid.isEmpty()) {
        enrollState = ENROLL_FAILED;
        updateLeds();
        Serial.println("[Enroll] FAILED — UID generation error");
        return;
      }
      enrollState = ENROLL_STORING;
      updateLeds();
      EnrolledUser u;
      u.name = pendingName;
      u.uniqueID = uid;
      u.enrolledAt = millis();
      if (enrollDB_save(u)) {
        enrollState = ENROLL_DONE;
        updateLeds();
        Serial.println("[Enroll] DONE — " + u.name + " → " + u.uniqueID);
      } else {
        enrollState = ENROLL_FAILED;
        updateLeds();
        Serial.println("[Enroll] FAILED — database full");
      }
    }
  }
}

void enrollReset() {
  fp_resetTemplates();
  pendingName = "";
  enrollState = ENROLL_IDLE;
  updateLeds();
}

String enrollStateString() {
  switch (enrollState) {
    case ENROLL_IDLE:       return "idle";
    case ENROLL_SCAN1_DONE: return "scan1_done";  // JS reads this → shows scan 2 button
    case ENROLL_SCAN2_DONE: return "scan2_done";  // JS reads this → shows "Processing..." disabled
    case ENROLL_PROCESSING: return "processing";
    case ENROLL_STORING:    return "storing";
    case ENROLL_DONE:       return "done";
    case ENROLL_FAILED:     return "failed";
  }
  return "unknown";
}

