void oledShowEnroll(EnrollState s, const String& name) {
  display.clearDisplay();
  display.setTextColor(SSD1306_WHITE);

  // Header bar
  display.fillRect(0, 0, 128, 12, SSD1306_WHITE);
  display.setTextSize(1);
  display.setTextColor(SSD1306_BLACK);
  display.setCursor(2, 2);
  display.print("ENROLLMENT MODE");
  display.setTextColor(SSD1306_WHITE);

  // Name (truncate if long)
  display.setCursor(2, 16);
  display.setTextSize(1);
  String n = name.length() > 16 ? name.substring(0, 15) + "~" : name;
  display.print(n.length() ? n : "---");

  // State label + progress bar
  String stateLabel;
  int    progW = 0;
  switch (s) {
    case ENROLL_IDLE:       stateLabel = "Ready - Scan 1";  progW = 0;   break;
    case ENROLL_SCAN1_DONE: stateLabel = "Scan 1 OK";       progW = 40;  break;
    case ENROLL_SCAN2_DONE: stateLabel = "Scan 2 OK";       progW = 65;  break;
    case ENROLL_PROCESSING: stateLabel = "Processing...";   progW = 80;  break;
    case ENROLL_STORING:    stateLabel = "Saving...";       progW = 95;  break;
    case ENROLL_DONE:       stateLabel = "ENROLLED!";       progW = 128; break;
    case ENROLL_FAILED:     stateLabel = "FAILED - Retry";  progW = 0;   break;
  }

  display.setCursor(2, 30);
  display.setTextSize(1);
  display.print(stateLabel);

  // Progress bar (at y=44)
  display.drawRect(0, 44, 128, 8, SSD1306_WHITE);
  if (progW > 0)
    display.fillRect(1, 45, progW - 1, 6, SSD1306_WHITE);

  // User count
  display.setCursor(2, 56);
  display.print("Users: ");
  display.print(dbCount);

  display.display();
}

// Rebuilt for the new authorization state machine.
void oledShowAuth(AuthState s, const String& uid, int attempts, unsigned long alarmRemainingSec) {
  display.clearDisplay();
  display.setTextColor(SSD1306_WHITE);

  display.fillRect(0, 0, 128, 12, SSD1306_WHITE);
  display.setTextSize(1);
  display.setTextColor(SSD1306_BLACK);
  display.setCursor(2, 2);
  display.print("AUTH MODE");
  display.setTextColor(SSD1306_WHITE);

  display.setCursor(2, 15);
  display.setTextSize(1);
  String u = uid.length() > 16 ? uid.substring(0, 15) + "~" : uid;
  display.print("ID: ");
  display.print(u.length() ? u : "---");

  String stateLabel;
  switch (s) {
    case AUTH_IDLE:         stateLabel = "Ready";             break;
    case AUTH_WAITING_SCAN: stateLabel = "Waiting for scan";  break;
    case AUTH_SCANNING:     stateLabel = "Scanning...";       break;
    case AUTH_PROCESSING:   stateLabel = "Processing scan";   break;
    case AUTH_VERIFYING:    stateLabel = "Verifying ID...";   break;
    case AUTH_GRANTED:      stateLabel = "";                  break; // shown big below
    case AUTH_DENIED:       stateLabel = "";                  break; // shown big below
    case AUTH_ALARM:        stateLabel = "";                  break; // shown big below
  }

  if (s == AUTH_GRANTED || s == AUTH_DENIED) {
    display.setTextSize(2);
    display.setCursor(s == AUTH_GRANTED ? 12 : 18, 30);
    display.print(s == AUTH_GRANTED ? "GRANTED" : "DENIED");
  } else if (s == AUTH_ALARM) {
    display.setTextSize(2);
    display.setCursor(24, 26);
    display.print("ALARM!");
    display.setTextSize(1);
    display.setCursor(10, 46);
    display.print("Resets in ");
    display.print(alarmRemainingSec);
    display.print("s");
  } else {
    display.setCursor(2, 30);
    display.setTextSize(1);
    display.print(stateLabel);
  }

  display.setCursor(2, 56);
  display.setTextSize(1);
  display.print("Fails:");
  display.print(attempts);
  display.print("/");
  display.print(MAX_FAILED_ATTEMPTS);
  display.print(" Users:");
  display.print(dbCount);

  display.display();
}

