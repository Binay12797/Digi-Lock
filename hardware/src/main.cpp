void setup() {
  Serial.begin(115200);
  pinMode(LED_GREEN,  OUTPUT);
  pinMode(LED_RED,    OUTPUT);
  pinMode(LED_YELLOW, OUTPUT);
  ledsOff();

  WiFi.begin(WIFI_SSID, WIFI_PASSWORD, WIFI_CHANNEL);
  Serial.print("Connecting to WiFi");
  while (WiFi.status() != WL_CONNECTED) { delay(100); Serial.print("."); }
  Serial.println(" Connected! IP: " + WiFi.localIP().toString());

  // ── Page routes ─────────────────────────────────────────
  server.on("/", sendHomePage);

  server.on(UriBraces("/mode/{}"), []() {
    int m = server.pathArg(0).toInt();
    if (m == 1 || m == 2) {
      currentMode = m;
      enrollReset();
      updateLeds();
      Serial.println("[Mode] → " + String(m == 1 ? "Enrollment" : "Authorization"));
    }
    if (currentMode == 1) sendEnrollmentPage();
    else if (currentMode == 2) sendAuthorizationPage();
    else sendHomePage();
  });

  // ── Enrollment REST API ──────────────────────────────────
  // These endpoints are called by the JS in the enrollment page.
  // Swap fetch() calls in the JS with real backend URLs later.

  server.on("/api/enroll/start", []() {
    String name = server.arg("name");
    if (name.isEmpty()) { server.send(400, "text/plain", "name required"); return; }
    enrollStart(name);
    server.send(200, "application/json", "{\"ok\":true}");
  });

  server.on("/api/enroll/scan1", []() {
    enrollScan1();
    server.send(200, "application/json",
      "{\"state\":\"" + enrollStateString() + "\"}");
  });

  server.on("/api/enroll/scan2", []() {
    enrollScan2();
    server.send(200, "application/json",
      "{\"state\":\"" + enrollStateString() + "\"}");
  });

  server.on("/api/enroll/state", []() {
    server.send(200, "application/json",
      "{\"state\":\"" + enrollStateString() + "\",\"name\":\"" + pendingName + "\"}");
  });

  server.on("/api/enroll/reset", []() {
    enrollReset();
    server.send(200, "application/json", "{\"ok\":true}");
  });

  // ── Database API ─────────────────────────────────────────
  server.on("/api/users", []() {
    server.send(200, "application/json", enrollDB_toJSON());
  });

  server.on("/api/db/clear", []() {
    enrollDB_clear();
    server.sendHeader("Location", "/mode/1");
    server.send(302);
  });

  // ── Authorization REST API ───────────────────────────────
  server.on("/api/auth/simulate", []() {
    bool match = server.arg("match") == "1";
    if (match) {
      ledSet(1,0,1); // G + Y on → granted
      delay(200);
    } else {
      ledSet(0,1,0); // R flash → denied
      delay(200);
      updateLeds();
    }
    server.sendHeader("Location", "/mode/2?result=" + String(match ? "ok" : "fail"));
    server.send(302);
  });

  server.begin();
  currentMode = 1; // start in enrollment mode
  updateLeds();
  Serial.println("[HTTP] Server started — http://localhost:8180");
}

// ──────────────────────────────────────────────────────────
// LOOP
// ──────────────────────────────────────────────────────────

void loop() {
  server.handleClient();
  enrollProcessLoop();   // drive the async state machine
  handleBlinkLeds();     // drive blink states for processing/failed
  delay(2);
}
