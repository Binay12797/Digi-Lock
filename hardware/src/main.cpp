int currentMode = 0;

// ── Enrollment sub-states ─────────────────────────────────
enum EnrollState {
  ENROLL_IDLE,        // waiting for user to trigger scan 1
  ENROLL_SCAN1_DONE,  // scan 1 captured, waiting for user to trigger scan 2
  ENROLL_SCAN2_DONE,  // scan 2 captured, processing starts automatically in loop()
  ENROLL_PROCESSING,  // firmware combining templates
  ENROLL_STORING,     // writing to database
  ENROLL_DONE,        // success
  ENROLL_FAILED       // timeout or error
};
EnrollState enrollState = ENROLL_IDLE;

unsigned long processingStartMs = 0;
const unsigned long PROCESSING_TIMEOUT_MS = 8000; // fail if > 8 s

// ── In-memory database (replace with MongoDB later) ───────
// Flexible struct — add fields (card ID, role, etc.) freely
struct EnrolledUser {
  String name;
  String uniqueID;   // combined fingerprint hash/ID
  unsigned long enrolledAt; // millis timestamp
};

const int DB_MAX = 50;
EnrolledUser enrolledDB[DB_MAX];
int dbCount = 0;

// ──────────────────────────────────────────────────────────
// DATABASE ABSTRACTION LAYER
// Swap these four functions for HTTP/MongoDB calls later.
// ──────────────────────────────────────────────────────────

bool enrollDB_save(const EnrolledUser& user) {
  if (dbCount >= DB_MAX) return false;
  enrolledDB[dbCount++] = user;
  Serial.println("[DB] Saved: " + user.name + " → " + user.uniqueID);
  return true;
}

String enrollDB_toJSON() {
  // Returns a JSON array for the /api/users endpoint
  String json = "[";
  for (int i = 0; i < dbCount; i++) {
    if (i > 0) json += ",";
    json += "{\"name\":\"" + enrolledDB[i].name
          + "\",\"uid\":\"" + enrolledDB[i].uniqueID
          + "\",\"ts\":" + String(enrolledDB[i].enrolledAt) + "}";
  }
  json += "]";
  return json;
}

bool enrollDB_findByUID(const String& uid) {
  for (int i = 0; i < dbCount; i++)
    if (enrolledDB[i].uniqueID == uid) return true;
  return false;
}

void enrollDB_clear() {
  dbCount = 0;
  Serial.println("[DB] Cleared.");
}

