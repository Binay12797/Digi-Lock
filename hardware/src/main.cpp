void updateDisplay() {
  if (currentMode == 1) {
    extern String pendingName;
    oledShowEnroll(enrollState, pendingName);
  } else if (currentMode == 2) {
    unsigned long remain = 0;
    if (authState == AUTH_ALARM) {
      unsigned long elapsed = millis() - alarmStartMs;
      remain = (elapsed < ALARM_DURATION_MS) ? (ALARM_DURATION_MS - elapsed) / 1000 : 0;
    }
    oledShowAuth(authState, authInputUID, failedAttempts, remain);
  } else {
    oledShowHome();
  }
}

