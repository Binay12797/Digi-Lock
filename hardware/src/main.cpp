// Tone helpers (non-blocking via millis)
// NOTE: your toolchain resolves the core v2 ledc API
// (ledcSetup/ledcAttachPin/ledcWrite/ledcDetachPin), so this
// stays on that API - same as your original code. Function
// names/behavior are unchanged.
unsigned long buzzerUntilMs = 0;
int buzzerFreq = 0;

void buzzerTone(int freq, int durationMs) {
  buzzerFreq    = freq;
  buzzerUntilMs = millis() + durationMs;
  ledcSetup(0, freq, 8);
  ledcAttachPin(BUZZER_PIN, 0);
  ledcWrite(0, 128); // 50% duty cycle
}

void buzzerOff() {
  ledcWrite(0, 0);
  ledcDetachPin(BUZZER_PIN);
  buzzerFreq = 0;
}

void handleBuzzer() {
  if (buzzerFreq > 0 && millis() >= buzzerUntilMs) {
    buzzerOff();
  }
}

