void ledsOff() {
  digitalWrite(LED_GREEN,  LOW);
  digitalWrite(LED_RED,    LOW);
  digitalWrite(LED_YELLOW, LOW);
}

// State → LED pattern mapping
// Blinking is approximated in-firmware; finer patterns need a timer ISR.
void ledSet(bool g, bool r, bool y) {
  digitalWrite(LED_GREEN,  g ? HIGH : LOW);
  digitalWrite(LED_RED,    r ? HIGH : LOW);
  digitalWrite(LED_YELLOW, y ? HIGH : LOW);
}

void updateLeds() {
  if (currentMode == 1) {
    switch (enrollState) {
      case ENROLL_IDLE:       ledSet(1,1,0); break; // G+R solid — ready
      case ENROLL_SCAN1_DONE: ledSet(1,0,0); break; // G solid — scan 1 done
      case ENROLL_SCAN2_DONE: ledSet(0,1,0); break; // R solid — scan 2 done, processing starting
      case ENROLL_PROCESSING: ledSet(1,1,0); break; // G+R — will blink in handleBlinkLeds()
      case ENROLL_STORING:    ledSet(1,1,1); break; // all on — storing
      case ENROLL_DONE:       ledSet(1,0,0); break; // G only — success
      case ENROLL_FAILED:     ledSet(0,1,0); break; // R only — will blink in handleBlinkLeds()
    }
  } else if (currentMode == 2) {
    ledSet(0,0,1);
  } else {
    ledsOff();
  }
}

unsigned long lastBlinkMs = 0;
bool blinkOn = false;
void handleBlinkLeds() {
  if (currentMode != 1) return;
  if (enrollState != ENROLL_PROCESSING && enrollState != ENROLL_FAILED) return;
  if (millis() - lastBlinkMs < 400) return;
  lastBlinkMs = millis();
  blinkOn = !blinkOn;
  if (enrollState == ENROLL_PROCESSING) {
    ledSet(blinkOn, blinkOn, 0); // G+R alternating blink
  } else if (enrollState == ENROLL_FAILED) {
    ledSet(0, blinkOn, 0);       // R blink only
  }
}

